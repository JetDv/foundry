#!/usr/bin/env python3
"""Rebuild library/_index/log.md from record frontmatter. Never hand-edit log.md."""
import pathlib
import re

LIB = pathlib.Path(__file__).resolve().parent.parent
FIELDS = ("workspace", "form", "stages", "shipped", "status", "destination")


def frontmatter(path):
    text = path.read_text(encoding="utf-8")
    match = re.match(r"^---\n(.*?)\n---", text, re.S)
    if not match:
        return None
    data = {}
    for line in match.group(1).splitlines():
        if ":" in line:
            key, _, value = line.partition(":")
            data[key.strip()] = value.strip().strip('"')
    return data


def main():
    rows = []
    for path in sorted(LIB.glob("*.md")):
        data = frontmatter(path)
        if not data:
            continue
        rows.append([path.stem] + [data.get(f, "") for f in FIELDS])

    lines = [
        "# Library index",
        "",
        "GENERATED by `rebuild.py`. Do not hand-edit — your changes are the next run's diff noise.",
        "",
        "| Slug | Workspace | Form | Stages | Shipped | Status | Destination |",
        "|---|---|---|---|---|---|---|",
    ]
    lines += ["| " + " | ".join(r) + " |" for r in rows] or ["| — | — | — | — | — | — | — |"]
    lines += ["", f"{len(rows)} record(s)."]

    (LIB / "_index" / "log.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote log.md — {len(rows)} record(s)")


if __name__ == "__main__":
    main()
